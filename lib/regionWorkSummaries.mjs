/** Use an exact recorded count only; general quote guidance is not job data. */
function compactRecordedStaff(staff) {
  const match = /^이번 현장은 (\d+)명이 들어가 (\d+)시간 동안 작업했습니다\.$/.exec(staff || '');
  return match ? `${match[1]}명 · ${match[2]}시간` : '';
}

export function summarizeRegionWork(serviceId, regionId, record) {
  const summary = REGION_WORK_SUMMARIES[`${serviceId}/${regionId}/${record.slug}`];
  const staff = compactRecordedStaff(record.facts?.staff);
  const titleParts = record.heading.split(' | ');
  return {
    // This is an existing complete title phrase, not a length-based excerpt.
    cardTitle: titleParts.length > 1 ? titleParts.slice(1).join(' | ') : record.heading,
    summaryFacts: [
      { label: '현장', value: record.facts?.location },
      { label: '작업 전', value: summary?.before || record.facts?.before },
      { label: '주요 작업', value: summary?.process || record.facts?.process },
      ...(staff ? [{ label: '인원·시간', value: staff }] : []),
    ].filter((fact) => fact.value),
    // Unknown future records retain their full closing text and note rather
    // than losing a limitation through automatic sentence truncation.
    summaryNote: summary
      ? summary.note || ''
      : [record.sections?.at(-1)?.body, record.note].filter(Boolean).join(' '),
  };
}

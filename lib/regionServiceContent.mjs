export const REGION_LANDING_SERVICES = Object.keys(SERVICE_TEMPLATES);

/**
 * Build the full body content for one region+service landing page.
 * Pure function — no DOM, safe to call from Node or the browser.
 */
export function buildRegionServiceContent(region, serviceId) {
  const tpl = SERVICE_TEMPLATES[serviceId];
  if (!tpl || !region) return null;

  const intro = tpl.buildIntro
    ? tpl.buildIntro(region)
    : `${region.name} ${tpl.serviceLabel} — ${region.story} 그만큼 ${tpl.serviceLabel}${josa(tpl.serviceLabel, '이', '가')} 필요한 현장을 꾸준히 만나 왔습니다. 현장 여건을 먼저 확인한 뒤 작업 범위를 정합니다.`;

  const faqs = tpl.faqTemplates.map(({ q, a }) => ({ q: q(region), a: a(region) }));

  return {
    serviceLabel: tpl.serviceLabel,
    intro,
    situations: tpl.situations,
    faqs,
    dongs: region.dongs,
  };
}
